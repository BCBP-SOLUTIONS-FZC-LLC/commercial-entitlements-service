# ---------------------------------------------------------------------------
# Patch swagger.json
# ---------------------------------------------------------------------------

def patch_json(path: Path) -> None:
    spec = json.loads(path.read_text())
    spec.pop("tags", None)
    ordered = {}
    for key, val in spec.items():
        if key == "securityDefinitions":
            ordered["tags"] = TAGS
        ordered[key] = val
    if "tags" not in ordered:
        ordered["tags"] = TAGS
    path.write_text(json.dumps(ordered, indent=4, ensure_ascii=False) + "\n")
    print(f"  patched {path.relative_to(ROOT)}")


# ---------------------------------------------------------------------------
# Patch swagger.yaml  (line-based insertion — avoids PyYAML dep)
# ---------------------------------------------------------------------------

def _yaml_scalar(s: str) -> str:
    if any(c in s for c in (':', '#', '[', ']', '{', '}', ',', '&', '*', '?', '|', '-', '<', '>', '=', '!', '%', '@', '`', '"', "'")):
        escaped = s.replace("'", "''")
        return f"'{escaped}'"
    return s


def patch_yaml(path: Path) -> None:
    lines = path.read_text().splitlines()
    cleaned: list[str] = []
    skip = False
    for line in lines:
        if line.startswith("tags:"):
            skip = True
            continue
        if skip:
            if line and not line.startswith(" ") and not line.startswith("-"):
                skip = False
            else:
                continue
        cleaned.append(line)

    tag_lines = ["tags:"]
    for t in TAGS:
        tag_lines.append(f"- description: {_yaml_scalar(t['description'])}")
        tag_lines.append(f"  name: {t['name']}")

    insert_at = next(
        (i for i, l in enumerate(cleaned) if l.startswith("securityDefinitions:")),
        len(cleaned),
    )
    result = cleaned[:insert_at] + tag_lines + cleaned[insert_at:]
    path.write_text("\n".join(result) + "\n")
    print(f"  patched {path.relative_to(ROOT)}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

swagger_dir = ROOT / "docs" / "swagger"

json_path = swagger_dir / "swagger.json"
yaml_path = swagger_dir / "swagger.yaml"

if not swagger_dir.exists():
    print(f"swagger dir not found: {swagger_dir}  — run 'make swag' first", file=sys.stderr)
    sys.exit(1)

if json_path.exists():
    patch_json(json_path)
else:
    print(f"  skipped {json_path.name} (not found)")

if yaml_path.exists():
    patch_yaml(yaml_path)
else:
    print(f"  skipped {yaml_path.name} (not found)")

print("patch-swagger-extensions.py done.")
